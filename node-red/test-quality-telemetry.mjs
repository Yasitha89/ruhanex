import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {qualitySnapshot,qualityLineProtocol,qualityInfluxPayload} from './quality-telemetry.mjs';
const payload={device:'RX-QLT-4000',total_count:2541,grade:3,grade_count:241,grade_counts:[0,1500,800,241,...Array(12).fill(0)],boot_id:12345678,sequence:2541,dropped_events:0};
const devices={'RX-QLT-4000':{enabled:true,line:'Keda 2',tenantId:'Rocell',siteId:'RCLH'}};
const settings={'Keda 2':{designCode:'2YKM.SM',tileSize:'60x60',TilesPerBox:4,designGrades:{1:'A',2:'B',3:'C',4:'D'}}};
const message={topic:'RX-QLT/4000/telemetry',payload:JSON.stringify(payload)};
const actual={device:'RX-QLT-4000',count:3,boot_id:3408083537,sequence:3,grade:3,grade_count:3,dropped_events:0,grade_counts:[0,0,0,3,...Array(12).fill(0)]};
assert.equal(qualitySnapshot({...message,payload:JSON.stringify(actual)},devices,settings,0).totalCount,3);
assert.equal(qualitySnapshot({...message,payload:{...actual,total_count:3}},devices,settings,0).totalCount,3);
assert.throws(()=>qualitySnapshot({...message,payload:{...actual,total_count:4}},devices,settings,0),/must match/);
assert.throws(()=>qualitySnapshot({...message,payload:{...actual,count:4}},devices,settings,0),/sum/);
assert.throws(()=>qualitySnapshot({...message,payload:{...actual,count:undefined}},devices,settings,0),/required/);
const s=qualitySnapshot(message,devices,settings,Date.parse('2026-11-17T00:00:00Z'));
assert.equal(s.line,'Keda 2');assert.equal(s.shiftDate,'2026-11-16');assert.equal(s.shift,'C');
assert.equal(s.gradeCounts[3],241);assert.equal(s.designGrades[4],'D');assert.equal(s.tilesPerBox,4);
const lp=qualityLineProtocol(s);
assert.match(lp,/grade_0_assignment=""/);assert.match(lp,/grade_1_assignment="A"/);assert.match(lp,/grade_3_assignment="C"/);assert.match(lp,/grade_3_boxes=241i/);
const undetected=qualitySnapshot({...message,payload:{...actual,count:1,grade:0,grade_count:1,grade_counts:[1,...Array(15).fill(0)]}},devices,settings,0);
assert.match(qualityLineProtocol(undetected),/undetected_boxes=1i/);
assert.match(qualityLineProtocol(undetected),/grade_0_assignment=""/);
const lastGrade=qualitySnapshot({...message,payload:{...actual,count:1,grade:15,grade_count:1,grade_counts:[...Array(15).fill(0),1]}},devices,{'Keda 2':{...settings['Keda 2'],designGrades:{15:'Last',16:'Unused'}}},0);
assert.match(qualityLineProtocol(lastGrade),/grade_15_assignment="Last"/);
assert.doesNotMatch(qualityLineProtocol(lastGrade),/grade_15_assignment="Unused"/);
assert.equal(s.schema,3);
settings['Keda 2'].designGrades[4]='Changed';assert.equal(s.designGrades[4],'D');
assert.throws(()=>qualitySnapshot(message,{},settings,0),/registered/);
assert.throws(()=>qualitySnapshot({...message,payload:{...payload,grade_count:800}},devices,settings,0),/grade_count/);
assert.throws(()=>qualitySnapshot({...message,payload:{...payload,total_count:2000}},devices,settings,0),/total_count/);
assert.throws(()=>qualitySnapshot({...message,topic:'RX-QLT/4001/telemetry'},devices,settings,0),/match/);
const nodes=JSON.parse(fs.readFileSync(new URL('./quality-telemetry.flow.json',import.meta.url)));
for(const n of nodes.filter(n=>n.type==='function'))new vm.Script(`(function(msg){${n.func}\n})`);
const memory=new Map();
const flow={get:k=>memory.get(k),set:(k,v)=>memory.set(k,v)};
const globals={get:k=>({devices,lineSettings:settings})[k]};
const errors=[];const node={error:e=>errors.push(e)};
const capture=vm.runInNewContext(`(function(msg){${nodes.find(n=>n.id==='qv2_capture').func}})`,{flow,global:globals,node});
const result=capture({...message,payload:JSON.stringify(actual)});
assert.equal(errors.length,0);assert.equal(result.payload[0].total_count,'3i');
assert.equal(result.payload[0].grade_3_assignment,'C');assert.equal(result.payload[1].device,'RX-QLT-4000');
const [fields,tags]=qualityInfluxPayload(s);
assert.equal(fields.time,s.receivedAt);assert.equal(fields.received_at_ms,`${s.receivedAt}i`);
assert.equal(fields.boot_id,'12345678');assert.equal(fields.grade_0_assignment,'');
assert.equal(tags.line,'Keda 2');assert.equal(fields.grade_3_boxes,'241i');
assert.equal(qualityInfluxPayload(undetected)[0].undetected_boxes,'1i');
const out=nodes.find(n=>n.id==='qv2_write');assert.equal(out.type,'influxdb out');
assert.equal(out.influxdb,'eef122fda5340dac');assert.equal(out.precisionV18FluxV20,'ms');
assert.equal(out.org,'Ruhanex');assert.equal(out.bucket,'RCLH');
assert.doesNotMatch(nodes.find(n=>n.id==='qv2_capture').func,/env.get|QUALITY_INFLUX/);
console.log('Quality telemetry mapping, validation, generated function and Influx Out payload tests passed.');
