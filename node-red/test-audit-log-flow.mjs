import assert from 'node:assert/strict';
import { prepareAudit, restoreAudit, nodes } from './build-audit-log-flow.mjs';
const make = () => ({ _msgid: 'test-id', req: { headers: { 'x-ruhanex-user': 'yasitha', 'x-ruhanex-role': 'Admin' } }, payload: { success: true }, statusCode: 200, headers: { 'Content-Type': 'application/json' }, audit: { action: 'line.tile_size_changed', username: 'fake', success: true, target: { line: 'Keda 1' }, changes: { before: { tileSize: '60x30', password: 'secret' }, after: { tileSize: '60x60', nested: { apiKey: 'secret', safe: 1 } } } } });
let msg = make();
const response = msg.payload;
assert.equal(prepareAudit(msg)[0], msg);
const record = msg.payload[0];
assert.equal(record.username, 'yasitha');
assert.ok(record.timestamp instanceof Date);
assert.equal(record.changes.before.password, undefined);
assert.equal(record.changes.after.nested.apiKey, undefined);
assert.equal(record.changes.after.nested.safe, 1);
assert.equal(record.requestId, 'test-id');
msg.payload = { acknowledged: true };
assert.equal(restoreAudit(msg)[0], msg);
assert.equal(msg.payload, response);
assert.equal(msg.statusCode, 200);
assert.equal(msg.audit, undefined);
msg = make(); prepareAudit(msg); msg.payload = { acknowledged: false };
assert.equal(restoreAudit(msg)[1].payload.success, true);
assert.ok(msg.auditError);
msg = make(); prepareAudit(msg); msg.error = { message: 'secret connection URL' };
assert.equal(restoreAudit(msg, true)[1].payload.success, true);
assert.equal(msg.error, undefined);
assert.ok(!JSON.stringify(msg.auditError).includes('secret'));
msg = make(); delete msg.req;
assert.equal(prepareAudit(msg)[1].statusCode, 200);
msg = make(); msg.audit.success = false;
assert.ok(prepareAudit(msg)[1].auditError);
for (const node of nodes.filter(node => node.type === 'function')) new Function('msg', node.func);
const ids = new Set(nodes.map(node => node.id));
for (const node of nodes) for (const target of (node.wires || []).flat()) assert.ok(ids.has(target));
console.log('PASS: audit identity, redaction, response preservation, failures, validation and generated wiring.');
