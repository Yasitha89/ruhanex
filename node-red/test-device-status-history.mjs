import assert from 'node:assert/strict';
import {logStatus,nodes} from './build-device-status-history-flow.mjs';
const values={};
const flow={get:k=>values[k],set:(k,v)=>values[k]=v};
const global={get:()=>({'RX-CNT-1006':{line:'Kiln 1'}})};
const node={error:message=>{throw Error(message);}};
const event=(status,retain=false,time=1000)=>({payload:{device:'RX-CNT-1006',sensorStatus:status,lastSeen:time},retain});
assert.equal(logStatus(event('Online',true),flow,global,node,1000),null);
const release=logStatus({statusHistoryRestore:true,payload:[]},flow,global,node,2000);
assert.equal(release[0].length,1);
const first=logStatus(release[0][0],flow,global,node,2000)[1].payload[0];
assert.equal(first.timestamp,1000);
assert.equal(first.fields.event_type,'initial_observation');
assert.equal(first.fields.retained,true);
assert.equal(logStatus(event('Online'),flow,global,node,3000),null);
const offline=logStatus(event('Offline',false,5000),flow,global,node,5000)[1].payload[0];
assert.equal(offline.fields.previous_status,'Online');
assert.equal(offline.fields.event_type,'status_change');
assert.equal(offline.tags.line,'Kiln 1');
assert.equal(offline.measurement,'device_status_events');
// Restart restores the last saved state, so retained duplicates add no outage.
logStatus({statusHistoryRestore:true,payload:[{_value:offline.fields.state_json}]},flow,global,node,6000);
assert.equal(logStatus(event('Offline',true,7000),flow,global,node,7000),null);
const retained=logStatus(event('Online',true,8000),flow,global,node,8000)[1].payload[0];
assert.equal(retained.fields.event_type,'retained_observation');
assert.equal(retained.fields.live_transition_observation,false);
assert.equal(retained.fields.previous_observation_duration_ms,3000);
for(const n of nodes.filter(n=>n.type==='function'))new Function('msg','flow','global','node',n.func);
console.log('PASS: startup buffering, status changes, duplicate suppression, baseline restore, retained observations and timestamps.');
