import assert from 'node:assert/strict';
import fs from 'node:fs';
const [node] = JSON.parse(fs.readFileSync(new URL('./counter-boot-id-alias.patch.flow.json', import.meta.url)));
const process = new Function('msg', 'flow', 'global', 'node', node.func);
const state = { previousRaw: 100, previousBootId: 'A', bootId: null, shiftCount: 10, deviceCount: 10, shiftName: '06-14', shiftDate: '2026-11-17' };
const counters = { 'RX-CNT-1000': state };
const flow = { get: key => key === 'counters' ? counters : undefined, set() {} };
const global = { get: key => key === 'counterConfig' ? { 'RX-CNT-1000': { enabled: true, line: 'Keda 1' } } : {} };
const runtime = { status() {}, warn(message) { throw Error(message); } };
const send = (count, boot_id) => process({ topic: 'RX-CNT/1000/telemetry', payload: { count, boot_id } }, flow, global, runtime);
const first = send(105, 'A');
assert.equal(state.bootId, 'A'); assert.equal(state.previousBootId, 'A');
assert.equal(first[1].payload[0].count_delta, 5); assert.equal(state.shiftCount, 15);
const reboot = send(3, 'B');
assert.equal(state.bootId, 'B'); assert.equal(state.previousBootId, 'B');
assert.equal(reboot[1].payload[0].count_delta, 3); assert.equal(state.shiftCount, 18);
assert.equal(reboot[1].payload[0].boot_id, 'B'); assert.equal(reboot[1].payload[1].eventType, 'new_boot');
send(3, 'B'); assert.equal(state.shiftCount, 18);
const [timer] = JSON.parse(fs.readFileSync(new URL('./downtime-boot-id.patch.flow.json', import.meta.url)));
const start = timer.func.indexOf('function sensorBootId(id)');
const end = timer.func.indexOf('\n}', start) + 2;
const read = new Function('counters', `return (${timer.func.slice(start, end)})`)(counters);
state.bootId = null; assert.equal(read('RX-CNT-1000'), 'B');
state.bootId = 'stale'; assert.equal(read('RX-CNT-1000'), 'B');
assert.equal(read('unknown'), null);
console.log('PASS: live previousBootId is recognized, bootId alias follows telemetry/reboots, delta/count/Influx output unchanged, stale aliases do not mask the active boot.');
