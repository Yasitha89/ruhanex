import assert from 'node:assert/strict';
import { defaults, shiftAt, transition, lineProtocol, engine, enrich, nodes } from './build-quality-sensor-flow.mjs';
const time = s => Date.parse(`2026-11-10T${s}:00+05:30`);
const counts = n => Object.fromEntries(Array.from({ length: 16 }, (_, i) => [String(i + 1).padStart(2, '0'), i === 0 ? n : 0]));
const telemetry = (n, boot = 'a') => ({ topic: 'RX-QLT/1000/telemetry', payload: { boot_id: boot, counts: counts(n) } });
let s = defaults(); s.config['RX-QLT-1000'].enabled = true;
const apply = (msg, at = time('10:00')) => { const r = transition(s, msg, at); s = r.state; return r; };
assert.equal(shiftAt(time('05:59')).key, '2026-11-09|22-06');
assert.equal(shiftAt(time('06:00')).key, '2026-11-10|06-14');
assert.equal(shiftAt(time('14:00')).shift, '14-22');
assert.equal(shiftAt(time('22:00')).shift, '22-06');
assert.equal(apply(telemetry(100)).signals[0].delta, 0);
assert.equal(apply(telemetry(105)).signals[0].delta, 5);
assert.equal(apply(telemetry(105)).signals[0].delta, 0);
const before = JSON.stringify(s);
assert.throws(() => transition(s, telemetry(104), time('10:01')), /rollback/);
assert.equal(JSON.stringify(s), before);
assert.throws(() => transition(s, telemetry(20000), time('10:01')), /excessive/);
assert.equal(apply(telemetry(3, 'b')).signals[0].delta, 3);
assert.throws(() => transition(s, telemetry(108, 'a'), time('10:01')), /retired/);
const cfg = structuredClone(s.config); cfg['RX-QLT-1000'].grades['01'].designCode = 'NEW'; cfg['RX-QLT-1000'].tilesPerBox = 6;
apply({ action: 'config', payload: cfg }); apply(telemetry(5, 'b'));
assert.equal(Object.values(s.devices['RX-QLT-1000'].rows).filter(r => r.gradeCode === '01').length, 2);
// Recovery uses a complete state, including baselines and product rows.
s = JSON.parse(JSON.stringify(s)); apply(telemetry(7, 'b'));
apply({ action: 'tick' }, time('14:00'));
const key = 'RX-QLT-1000|2026-11-10|06-14';
assert.equal(s.pending[key].totalBoxes, 12);
assert.equal(s.pending[key].totalTiles, 56);
assert.equal(s.pending[key].quality, 100);
apply(telemetry(9, 'b'), time('14:01'));
assert.equal(Object.values(s.devices['RX-QLT-1000'].rows).reduce((a,r) => a+r.boxes,0), 2);
const protocol = lineProtocol({ state: s, signals: [] });
assert.ok(protocol.startsWith('quality_checkpoint,scope=quality-v1 state_json="'));
assert.equal(protocol.split('\n').length, 1);
const values = new Map([['qualityReady', true], ['qualityState', s]]);
const flow = { get: k => values.get(k), set: (k,v) => values.set(k,v) };
const warnings = [];
const node = { warn: s => warnings.push(s), error: s => warnings.push(s) };
const env = { get: k => ({ QUALITY_INFLUX_URL: 'http://localhost:8086', QUALITY_INFLUX_TOKEN: 'test' })[k] };
const result = engine(telemetry(10, 'b'), flow, node, env);
assert.equal(result[0].method, 'POST');
assert.equal(flow.get('qualityState').revision, s.revision); // uncommitted
assert.equal(flow.get('qualityBusy'), true);
engine({action:'tick'},flow,node,env);
assert.equal(flow.get('qualityState').revision, s.revision);
engine({ action: 'commit', qualityRevision: result[0].qualityRevision },flow,node,env);
assert.equal(flow.get('qualityState').revision, s.revision+1);
const doc = {payload:{lineStats:{device:'RX-CNT-1000',shift:'06-14',shiftDate:'2026-11-10',availability:80,performance:90}}};
enrich(doc,flow); assert.equal(doc.payload.lineStats.ole,72);
assert.equal(doc.qualitySummaryKey,key);
s = transition(s,{action:'saved',summaryKey:key},time('14:02')).state;
assert.equal(s.pending[key],undefined); assert.equal(s.completed[key].totalTiles,56);
const ids = new Set(nodes.map(n => n.id));
for(const n of nodes){
  if(n.type==='function') new Function('msg','flow','node','env',n.func);
  for(const target of (n.wires||[]).flat()) assert.ok(ids.has(target),target);
}
assert.ok(!nodes.some(n => n.type==='mqtt out'));
console.log('PASS: boot deltas, duplicates, rejection, product changes, recovery, shifts, write gating, enrichment and wiring.');
