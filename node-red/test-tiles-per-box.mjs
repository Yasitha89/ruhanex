import assert from 'node:assert/strict';
import fs from 'node:fs';
import { KEDA_TILE_SIZES, validateTilesPerBox } from '../src/utils/ratedLineSpeeds.js';
import { buildLineSettingsPayload } from '../src/utils/lineSettings.js';
import { routeSpeeds, prepareSpeedWrite, finishSpeedWrite, preserveSpeeds } from './build-keda-saved-speeds-flow.mjs';
const current = { tileSize: '60x60', designCode: 'ABC', lineSpeed: 12, plannedDowntime: 30, stopDelayMs: 60000,
  maxPulseGapMs: 10000, requiredRunTimeMs: 60000, productionRunId: 'same-run', savedSpeeds: { '60x60': 12 }, savedTilesPerBox: { '60x60': 4 } };
const state = { settingsReady: true, lineSettings: { 'Keda 1': current } };
const global = { get: k => state[k], set: (k, v) => { state[k] = v; } };
for (const [line, sizes] of Object.entries(KEDA_TILE_SIZES)) {
  const boxes = Object.fromEntries(sizes.map((size, i) => [size, i + 2]));
  assert.deepEqual(validateTilesPerBox(line, boxes), boxes);
  const request = { req: { headers: { 'x-ruhanex-role': 'Manager' } }, payload: { line, settingsAction: 'saveTilesPerBox', savedTilesPerBox: boxes } };
  assert.equal(routeSpeeds(request, global)[1], request);
  request.payload = { settings: { [line]: current } };
  prepareSpeedWrite(request);
  assert.deepEqual(request.payload[1].$set[`settings.${line}.savedTilesPerBox`], boxes);
  assert.equal(request.payload[1].$set[`settings.${line}.lineSpeed`], undefined);
  assert.equal(request.payload[1].$set[`settings.${line}.productionRunId`], undefined);
  request.payload = { acknowledged: true, matchedCount: 1 }; finishSpeedWrite(request, global);
  assert.deepEqual(request.payload.settings.savedTilesPerBox, boxes);
  assert.equal(request.payload.settings.lineSpeed, 12);
  const ordinary = { savedLine: line, savedSettings: { ...current }, req: { body: {} } };
  preserveSpeeds(ordinary, global);
  assert.deepEqual(ordinary.savedSettings.savedTilesPerBox, boxes);
  const adminPayload = buildLineSettingsPayload(line, { ...current, savedTilesPerBox: boxes }, current, true);
  assert.deepEqual(adminPayload.savedTilesPerBox, boxes);
}
for (const bad of [0, -1, 1.5, '4', Infinity]) assert.throws(() => validateTilesPerBox('Keda 1', { '60x60': bad }));
assert.throws(() => validateTilesPerBox('Keda 1', { '120x80': 4 }), /Unsupported/);
assert.deepEqual(validateTilesPerBox('Keda 1', { '60x60': null }), {});
const denied = { req: { headers: { 'x-ruhanex-role': 'Line Supervisor' } }, payload: { line: 'Keda 1', settingsAction: 'saveTilesPerBox', savedTilesPerBox: {} } };
assert.equal(routeSpeeds(denied, global)[2].statusCode, 403);
denied.req.headers['x-ruhanex-role'] = 'Manager'; denied.payload = { line: 'Kiln 1', settingsAction: 'saveTilesPerBox', savedTilesPerBox: {} };
assert.equal(routeSpeeds(denied, global)[2].statusCode, 400);
state.lineSettings['Keda 1'] = { ...current, TilesPerBox: 8, savedTilesPerBox: { '60x30': 8, '60x60': 4 } };
const manual = { savedLine: 'Keda 1', savedSettings: { ...current }, req: { body: { TilesPerBox: 6, savedTilesPerBox: { '60x60': 999 } } } };
assert.equal(preserveSpeeds(manual, global)[0], manual);
assert.equal(manual.savedSettings.TilesPerBox, 6);
assert.equal(manual.savedSettings.savedTilesPerBox['60x60'], 4);
const changed = { savedLine: 'Keda 1', savedSettings: { ...current, tileSize: '60x30' }, req: { body: { TilesPerBox: 6 } } };
preserveSpeeds(changed, global); assert.equal(changed.savedSettings.TilesPerBox, 8);
const noPreset = { savedLine: 'Keda 1', savedSettings: { ...current, tileSize: '40x40' }, req: { body: { TilesPerBox: 6 } } };
preserveSpeeds(noPreset, global); assert.equal(noPreset.savedSettings.TilesPerBox, 6);
const adminSave = { savedLine: 'Keda 1', savedSettings: { ...current }, req: { body: {} } };
preserveSpeeds(adminSave, global); assert.equal(adminSave.savedSettings.TilesPerBox, 8);
const activePayload = buildLineSettingsPayload('Keda 1', state.lineSettings['Keda 1'], { ...current, TilesPerBox: 6 }, false);
assert.equal(activePayload.TilesPerBox, 6); assert.equal(activePayload.savedTilesPerBox['60x60'], 4);
assert.equal(buildLineSettingsPayload('Keda 1', state.lineSettings['Keda 1'], current, true).TilesPerBox, 8);
for (const n of JSON.parse(fs.readFileSync(new URL('./keda-line-settings-save.patch.flow.json', import.meta.url)))) if (n.type === 'function') new Function('msg', 'global', 'node', n.func);
console.log('PASS: all Keda sizes, Manager save, packing-only database update, preservation on normal/Admin saves, validation, role/line rejection and directly wired flow syntax.');
